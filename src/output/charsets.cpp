void putUtf8(std::string& out, uint32_t cp) {
    if (cp < 0x80) {
        out.push_back(static_cast<char>(cp));
    } else if (cp < 0x800) {
        out.push_back(static_cast<char>(0xC0 | (cp >> 6)));
        out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
    } else {
        out.push_back(static_cast<char>(0xE0 | (cp >> 12)));
        out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
        out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
    }
}

// the next code point of a UTF-8 text; a broken sequence gives 0xFFFD
uint32_t nextUtf8(const std::string& s, size_t& i) {
    uint8_t c = static_cast<uint8_t>(s[i++]);
    if (c < 0x80) return c;
    int more = (c & 0xE0) == 0xC0 ? 1 : (c & 0xF0) == 0xE0 ? 2 : (c & 0xF8) == 0xF0 ? 3 : -1;
    if (more < 0) return 0xFFFD;
    uint32_t cp = c & (0x3F >> more);
    for (int k = 0; k < more; k++) {
        if (i >= s.size() || (static_cast<uint8_t>(s[i]) & 0xC0) != 0x80) return 0xFFFD;
        cp = (cp << 6) | (static_cast<uint8_t>(s[i++]) & 0x3F);
    }
    return cp;
}

bool validUtf8(const uint8_t* data, size_t len) {
    std::string s(reinterpret_cast<const char*>(data), len);
    for (size_t i = 0; i < s.size();)
        if (nextUtf8(s, i) == 0xFFFD) return false;
    return true;
}

