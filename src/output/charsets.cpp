bool dabLabelToUtf8(const uint8_t* data, size_t len, uint8_t charset, std::string& out) {
    out.clear();
    switch (charset) {
    case DAB_CHARSET_EBU_LATIN:
        for (size_t i = 0; i < len && data[i]; i++) {
            uint16_t cp = EBU_LATIN[data[i]];
            if (cp != SKIP) putUtf8(out, cp);
        }
        return true;
    case DAB_CHARSET_UCS2_BE:
        for (size_t i = 0; i + 1 < len; i += 2) {
            uint16_t cp = static_cast<uint16_t>(data[i] << 8 | data[i + 1]);
            if (!cp) break;
            if (cp >= 0xD800 && cp < 0xE000) cp = 0xFFFD;  // no surrogates in UCS-2
            putUtf8(out, cp);
        }
        return true;
    case DAB_CHARSET_UTF8: {
        size_t n = 0;
        while (n < len && data[n]) n++;
        if (!validUtf8(data, n)) return false;
        out.assign(reinterpret_cast<const char*>(data), n);
        return true;
    }
    default:
        return false;
    }
}

std::string utf8ToRds(const std::string& utf8) {
    static const std::map<uint32_t, uint8_t> to_rds = [] {
        std::map<uint32_t, uint8_t> m;
        for (int c = 0xFE; c >= 0x20; c--)
            if (RDS_G0[c]) m[RDS_G0[c]] = static_cast<uint8_t>(c);
        return m;
    }();
    std::string out;
    for (size_t i = 0; i < utf8.size();) {
        auto it = to_rds.find(nextUtf8(utf8, i));
        out.push_back(static_cast<char>(it != to_rds.end() ? it->second : '?'));
    }
    return out;
}

